"""Generate overrides/partials/page-tocs.html for the BabelBrain docs.

Zensical only gives the theme the table of contents (TOC) of the page being
viewed, so in the left panel the other pages of a section show just their
title. This script parses every page listed in `nav` of mkdocs.yml with the
same Markdown extensions Zensical uses, extracts its headings, and writes a
Jinja macro with each page's TOC pre-rendered. overrides/partials/nav-item.html
calls that macro so every page of a section shows its headings.

Run automatically by `make build` / `make serve`; run it by hand
(`python gen_page_tocs.py`) after editing headings while `make serve` is up.
"""

import html
from pathlib import Path

import markdown
import yaml

ROOT = Path(__file__).resolve().parent
CONFIG = ROOT / "mkdocs.yml"
OUTPUT = ROOT / "overrides" / "partials" / "page-tocs.html"


class _Loader(yaml.SafeLoader):
    """SafeLoader that tolerates !!python/name tags sometimes used in mkdocs.yml."""


_Loader.add_multi_constructor("tag:yaml.org,2002:python/", lambda *a: None)


def nav_files(items):
    for item in items or []:
        value = next(iter(item.values())) if isinstance(item, dict) else item
        if isinstance(value, list):
            yield from nav_files(value)
        elif isinstance(value, str) and value.endswith(".md"):
            yield value


def markdown_extensions(config):
    names, configs = [], {}
    for ext in config.get("markdown_extensions", []):
        if isinstance(ext, dict):
            (name, opts), = ext.items()
            names.append(name)
            configs[name] = opts or {}
        else:
            names.append(ext)
    return names, configs


def page_url(src, use_directory_urls):
    stem = src[: -len(".md")]
    if not use_directory_urls:
        return stem + ".html"
    if stem == "index" or stem.endswith("/index"):
        return stem[: -len("index")]
    return stem + "/"


def text(s):
    # escape for HTML and neutralise Jinja delimiters
    return html.escape(html.unescape(s)).replace("{", "&#123;").replace("}", "&#125;")


def render_items(tokens, indent="  "):
    out = []
    for t in tokens:
        out.append(f'{indent}<li class="md-nav__item">')
        out.append(f'{indent}  <a href="{{{{ prefix }}}}#{t["id"]}" class="md-nav__link">'
                   f'<span class="md-ellipsis"><span class="md-typeset">{text(t["name"])}'
                   f"</span></span></a>")
        if t["children"]:
            out.append(f'{indent}  <nav class="md-nav" aria-label="{text(t["name"])}">')
            out.append(f'{indent}    <ul class="md-nav__list">')
            out.extend(render_items(t["children"], indent + "      "))
            out.append(f"{indent}    </ul>")
            out.append(f"{indent}  </nav>")
        out.append(f"{indent}</li>")
    return out


def main():
    config = yaml.load(CONFIG.read_text(encoding="utf-8"), Loader=_Loader)
    docs_dir = ROOT / config.get("docs_dir", "docs")
    use_dir_urls = config.get("use_directory_urls", True)
    names, configs = markdown_extensions(config)

    blocks = []
    for src in dict.fromkeys(nav_files(config.get("nav"))):
        path = docs_dir / src
        if not path.exists():
            continue
        md = markdown.Markdown(extensions=names, extension_configs=configs)
        md.convert(path.read_text(encoding="utf-8"))
        toc = md.toc_tokens
        # same rule as overrides/partials/toc.html: a single top H1 is the
        # page title, so show its children; several H1s are all kept
        if len(toc) == 1 and toc[0]["level"] == 1:
            toc = toc[0]["children"]
        if not toc:
            continue
        key = page_url(src, use_dir_urls)
        blocks.append((key, render_items(toc, "      ")))

    lines = [
        "{#- GENERATED by gen_page_tocs.py from mkdocs.yml - do not edit by hand -#}",
        "{% macro render(key, prefix) %}",
    ]
    for i, (key, items) in enumerate(blocks):
        lines.append(f'{"{% if" if i == 0 else "{% elif"} key == "{key}" %}}')
        lines.append('  <nav class="md-nav md-nav--secondary md-nav--sibling-toc">')
        lines.append('    <ul class="md-nav__list">')
        lines.extend(items)
        lines.append("    </ul>")
        lines.append("  </nav>")
    if blocks:
        lines.append("{% endif %}")
    lines.append("{% endmacro %}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"gen_page_tocs: wrote TOCs for {len(blocks)} pages -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
